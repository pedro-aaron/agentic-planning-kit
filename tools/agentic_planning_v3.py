@dataclass(frozen=True, order=True)
class Issue:
    code: str
    path: str
    message: str

    def line(self) -> str:
        location = self.path or "."
        return f"ERROR {self.code} {location}: {self.message}"


@dataclass(frozen=True)
class Artifact:
    path: Path
    relative_path: str
    expected_type: str
