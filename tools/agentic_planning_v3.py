def command_render(args: argparse.Namespace) -> int:
    root = _root_from_args(args)
    artifacts, issues = validate_workspace(root, include_claims=True)
    if issues:
        _print_issues(issues)
        return 1
    outputs, output_issues = expected_outputs(root, artifacts)
    if output_issues:
        _print_issues(output_issues)
        return 1
    if args.check:
        mismatches = []
        for target, expected in outputs.items():
            relative = _relative(root, target)
            if not target.is_file():
                mismatches.append(Issue("GENERATED_VIEW_MISSING", relative, "run render --write"))
            elif target.read_bytes() != expected:
                mismatches.append(Issue("GENERATED_VIEW_STALE", relative, "content differs from deterministic render"))
        if mismatches:
            _print_issues(mismatches)
            return 1
        print(f"OK render --check: {len(outputs)} generated views are current")
        return 0
    _write_outputs_atomically(outputs)
    for target in sorted(outputs, key=lambda path: path.as_posix()):
        print(f"WROTE {_relative(root, target)} {sha256_bytes(outputs[target])}")
    return 0


def _path_matches_pattern(path: str, pattern: str) -> bool:
    normalized = path.replace("\\", "/").lstrip("./")
    target = pattern.replace("\\", "/").lstrip("./")
    if target.endswith("/**"):
        prefix = target[:-3].rstrip("/")
        return normalized == prefix or normalized.startswith(prefix + "/")
    return normalized == target


def _git(root: Path, arguments: Sequence[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *arguments],
        cwd=root,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )


def _git_changed_paths(root: Path, base: str) -> tuple[set[str], list[Issue]]:
    verify = _git(root, ["rev-parse", "--verify", f"{base}^{{commit}}"])
    if verify.returncode != 0:
        return set(), [Issue("GIT_BASE_INVALID", base, verify.stderr.strip() or "base is not a commit")]
    commands = [
        ["diff", "--name-only", "--diff-filter=ACDMRTUXB", f"{base}...HEAD"],
        ["diff", "--name-only", "--diff-filter=ACDMRTUXB"],
        ["diff", "--cached", "--name-only", "--diff-filter=ACDMRTUXB"],
        ["ls-files", "--others", "--exclude-standard"],
    ]
    changed: set[str] = set()
    for command in commands:
        result = _git(root, command)
        if result.returncode != 0:
            return set(), [Issue("GIT_DIFF_FAILED", ".", result.stderr.strip() or "git diff failed")]
        changed.update(line.strip().replace("\\", "/") for line in result.stdout.splitlines() if line.strip())
    return changed, []


def _exists_at_git_ref(root: Path, git_ref: str, path: str) -> bool:
    result = _git(root, ["ls-tree", "-r", "--name-only", git_ref, "--", path])
    return result.returncode == 0 and path in {line.strip() for line in result.stdout.splitlines()}


def _scope_covers(path: str, scope: dict[str, Any]) -> bool:
    scope_path = str(scope.get("path", ""))
    if scope.get("kind") == "exact":
        return path == scope_path
    return path == scope_path or path.startswith(scope_path + "/")


def _candidate_scope_issues(
    root: Path,
    base: str,
    changed: set[str],
    artifacts: Sequence[Artifact],
    protected_patterns: Sequence[str],
) -> list[Issue]:
    issues: list[Issue] = []
    ignored = _git(
        root,
        ["ls-files", "--others", "--ignored", "--exclude-standard", "--", ".agentic_planning"],
    )
    if ignored.returncode == 0:
        for ignored_path in sorted(line.strip().replace("\\", "/") for line in ignored.stdout.splitlines() if line.strip()):
            if "/.local/" not in ignored_path and not ignored_path.startswith(".agentic_planning/.local/"):
                issues.append(
                    Issue(
                        "PLANNING_SOURCE_IGNORED",
                        ignored_path,
                        "canonical planning files must be force-included by the repository .gitignore",
                    )
                )
    entity_ids: set[str] = set()
    product_paths: list[str] = []
    entity_source = re.compile(r"^\.agentic_planning/(features|analyses|projects)/([^/]+)/(.+)$")
    for path in sorted(changed):
        if any(_path_matches_pattern(path, pattern) for pattern in protected_patterns):
            continue
        match = entity_source.match(path)
        if match:
            entity_dir = match.group(2)
            entity_id = entity_dir.split("--", 1)[0]
            if not re.match(r"^(ftr|ana|prj)_[0-9a-f-]+$", entity_id):
                issues.append(Issue("ENTITY_PATH_INVALID", path, "entity directory has no valid prefixed identity"))
                continue
            entity_ids.add(entity_id)
            current = root / path
            if not current.is_file():
                issues.append(Issue("IMMUTABLE_SOURCE_DELETED", path, "entity-owned sources are create-only"))
            elif _exists_at_git_ref(root, base, path):
                issues.append(Issue("IMMUTABLE_SOURCE_CHANGED", path, "existing entity-owned source was modified"))
            continue
        if path.startswith(".agentic_planning/"):
            issues.append(Issue("PLANNING_PATH_UNOWNED", path, "path is neither an entity-owned source nor an authorized protected output"))
            continue
        product_paths.append(path)

    descriptors = {
        str(item.data.get("entity_id")): item for item in _by_type(artifacts, "entity_descriptor")
    }
    manifests = _by_type(artifacts, "entity_manifest")
    events = _by_type(artifacts, "event")
    manifests_by_revision = {str(item.data.get("revision_id")): item for item in manifests}
    contract = _by_type(artifacts, "contract")[0].data
    local_repo_id = str(contract["repo_id"])
    scopes: list[tuple[str, dict[str, Any]]] = []
    for entity_id in sorted(entity_ids):
        revision_id = _current_revision_id(entity_id, descriptors, manifests, events)
        manifest = manifests_by_revision.get(str(revision_id))
        if manifest is None or manifest.data.get("entity_id") != entity_id:
            issues.append(Issue("SCOPE_OWNER_INVALID", entity_id, "changed entity has no current manifest"))
            continue
        for scope in manifest.data.get("write_scopes", []):
            if scope.get("repository_id") == local_repo_id:
                scopes.append((entity_id, scope))

    for path in product_paths:
        if not entity_ids:
            issues.append(Issue("SCOPE_OWNER_MISSING", path, "product change has no changed entity-owned receipt/event/source"))
            continue
        if not any(_scope_covers(path, scope) for _, scope in scopes):
            owners = ", ".join(sorted(entity_ids))
            issues.append(Issue("WRITE_SCOPE_VIOLATION", path, f"not covered by current manifest scopes for {owners}"))
    return issues


def _catalog_change_issues(
    root: Path,
    base: str,
    changed: set[str],
    artifacts: Sequence[Artifact],
    catalog_path: str,
) -> list[Issue]:
    applied_ids = {
        str(delta_id)
        for receipt in _by_type(artifacts, "reconciliation_receipt")
        if receipt.data.get("status") == "SUCCEEDED"
        for delta_id in receipt.data.get("applied_delta_ids", [])
    }
    deltas = [
        item
        for item in _by_type(artifacts, "map_delta")
        if str(item.data.get("delta_id")) in applied_ids
    ]
    issues: list[Issue] = []
    prefix = catalog_path.rstrip("/") + "/"
    for path in sorted(item for item in changed if item.startswith(prefix) and item.endswith(".json")):
        item_id = PurePosixPath(path).stem
        existed = _exists_at_git_ref(root, base, path)
        exists = (root / path).is_file()
        operation = "REPLACE" if existed and exists else "ADD" if exists else "REMOVE"
        matches = [
            delta
            for delta in deltas
            if delta.data.get("item_id") == item_id and delta.data.get("operation") == operation
        ]
        if len(matches) != 1:
            issues.append(
                Issue(
                    "CATALOG_CHANGE_UNATTRIBUTED",
                    path,
                    f"{operation} requires exactly one successfully applied map delta for {item_id}",
                )
            )
    return issues


def command_protected(args: argparse.Namespace) -> int:
    root = _root_from_args(args)
    artifacts, issues = validate_workspace(root, include_claims=True)
    if issues:
        _print_issues(issues)
        return 1
    contract_artifacts = _by_type(artifacts, "contract")
    contract = contract_artifacts[0].data
    changed, git_issues = _git_changed_paths(root, args.base)
    if git_issues:
        _print_issues(git_issues)
        return 1
    protected_patterns = contract["protected_paths"]
    protected_changed = sorted(
        path for path in changed if any(_path_matches_pattern(path, pattern) for pattern in protected_patterns)
    )
    scope_issues = _candidate_scope_issues(root, args.base, changed, artifacts, protected_patterns)
    if scope_issues:
        _print_issues(scope_issues)
        return 1
    if not protected_changed:
        print("OK protected: immutable sources and product scopes are valid; no protected global paths changed")
        return 0
    if not args.integration:
        _print_issues(
            [
                Issue("PROTECTED_PATH_CHANGED", path, "ordinary branches cannot modify this global path")
                for path in protected_changed
            ]
        )
        return 1

    catalog_issues = _catalog_change_issues(
        root, args.base, changed, artifacts, str(contract["catalog_path"])
    )
    if catalog_issues:
        _print_issues(catalog_issues)
        return 1

    outputs, output_issues = expected_outputs(root, artifacts)
    generated = {_relative(root, target) for target in outputs}
    catalog_pattern = contract["catalog_path"] + "/**"
    unsupported = [
        path
        for path in protected_changed
        if path not in generated
        and not _path_matches_pattern(path, catalog_pattern)
        and re.fullmatch(r"\.agentic_planning/reconciliations/rec_[0-9a-f-]+/receipt\.json", path) is None
    ]
    if unsupported:
        _print_issues(
            [
                Issue("INTEGRATION_PATH_UNSUPPORTED", path, "control plane cannot prove this protected edit")
                for path in unsupported
            ]
        )
        return 1
    for target, expected in outputs.items():
        relative = _relative(root, target)
        if not target.is_file() or target.read_bytes() != expected:
            output_issues.append(
                Issue("GENERATED_VIEW_STALE", relative, "integration view must exactly match deterministic render")
            )
    if output_issues:
        _print_issues(output_issues)
        return 1
    print(f"OK protected --integration: {len(protected_changed)} protected changes are reproducible")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Agentic Planning Kit v3 deterministic control plane"
    )
    parser.add_argument("--version", action="version", version=TOOL_VERSION)
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate_parser = subparsers.add_parser("validate", help="validate schemas, IDs, references, events, paths, and active claims")
    validate_parser.add_argument("--root", default=".", help="workspace root (default: current directory)")
    validate_parser.add_argument("paths", nargs="*", help="optional artifact paths; omit for the complete workspace")
    validate_parser.set_defaults(handler=command_validate)

    claims_parser = subparsers.add_parser("claims", help="check active write scopes and resource claims")
    claims_parser.add_argument("--root", default=".", help="workspace root (default: current directory)")
    claims_parser.set_defaults(handler=command_claims)

    render_parser = subparsers.add_parser("render", help="render generated index and workspace map")
    render_parser.add_argument("--root", default=".", help="workspace root (default: current directory)")
    render_mode = render_parser.add_mutually_exclusive_group(required=True)
    render_mode.add_argument("--check", action="store_true", help="fail if generated views differ")
    render_mode.add_argument("--write", action="store_true", help="replace generated views from validated sources")
    render_parser.set_defaults(handler=command_render)

    protected_parser = subparsers.add_parser("protected", help="enforce the protected global-path policy against a Git base")
    protected_parser.add_argument("--root", default=".", help="workspace root (default: current directory)")
    protected_parser.add_argument("--base", required=True, help="Git commit/ref used as the comparison base")
    protected_parser.add_argument(
        "--integration",
        action="store_true",
        help="allow catalog changes and exact deterministic generated views for RECONCILE_MAIN",
    )
    protected_parser.set_defaults(handler=command_protected)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.handler(args))
    except (OSError, ValueError) as exc:
        print(f"ERROR CONTROL_PLANE_FAILED .: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
